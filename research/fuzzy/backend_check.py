#!/usr/bin/env python3
"""Independently check the installed corrected backend with exact coefficients.

No backend scalar conversion, floating-point sampling, or clipping is used.
Run from any working directory:

    python3 research/fuzzy/backend_check.py

By default this compiles only backend_probe.cpp into a temporary directory and
links the existing build/fraxis/libmdn.so; it does not rebuild that library.
Compiler output is appended to --build-log. Full emitted grids stay in --work.
Only the compact checks/provenance summary is written into the repository.
"""

from __future__ import annotations

import argparse
from collections import defaultdict
from functools import lru_cache
import hashlib
import itertools
import json
import math
from pathlib import Path
import platform
import shlex
import subprocess
import time


REPOSITORY = Path(__file__).resolve().parents[2]
DEFAULT_WORK = Path("/tmp/mdn-fuzzy-01a12881")
DEFAULT_LOG = Path.home() / "output_01a12881-e6c8-7cb2-a1d2-7c899e17aa69.log"
GRID_NAMES = ("L_N", "R_M", "L_P", "R_Q", "F", "FX", "FY", "F2")


def grid(cells):
    return {(int(x), int(y)): int(d) for x, y, d in cells if d}


def add(*grids):
    result = defaultdict(int)
    for value in grids:
        for coordinate, coefficient in value.items():
            result[coordinate] += coefficient
    return {coordinate: coefficient for coordinate, coefficient in result.items() if coefficient}


def scale(value, coefficient):
    return {coordinate: coefficient * digit for coordinate, digit in value.items() if coefficient * digit}


def multiply(*grids):
    result = {(0, 0): 1}
    for value in grids:
        product = defaultdict(int)
        for (x, y), a in result.items():
            for (u, v), b in value.items():
                product[x + u, y + v] += a * b
        result = {coordinate: coefficient for coordinate, coefficient in product.items() if coefficient}
    return result


@lru_cache(maxsize=8192)
def binomial_row(degree, base):
    return tuple(math.comb(degree, k) * base ** (degree - k) * (-1 if k % 2 else 1)
                 for k in range(degree + 1))


def zero_mod_carry(value, base):
    """Clear Laurent powers and substitute Y=base-X, comparing every coefficient.

    For finite integer Laurent polynomials this tests exactly the ideal
    generated by X+Y-base, without assigning X or Y a scalar magnitude.
    """
    if not value:
        return True
    min_x = min(x for x, _ in value)
    min_y = min(y for _, y in value)
    coefficients = defaultdict(int)
    for (x, y), coefficient in value.items():
        for k, term in enumerate(binomial_row(y - min_y, base)):
            coefficients[x - min_x + k] += coefficient * term
    return not any(coefficients.values())


def equal_mod_carry(left, right, base):
    return zero_mod_carry(add(left, scale(right, -1)), base)


def cascade(index, direction):
    if direction == "X":
        return {(-k - 1, k): (-1 if k % 2 else 1) for k in range(index + 1)}
    return {(k, -k - 1): (-1 if k % 2 else 1) for k in range(index + 1)}


def qpower(exponent):
    return {(-exponent, exponent): -1 if exponent % 2 else 1}


def boundary_factor(exponent):
    return add({(0, 0): 1}, scale(qpower(exponent), -1))


def compile_probe(args, executable):
    command = [args.compiler, "-std=c++17", "-O2", "-I", str(REPOSITORY / "library/include"),
               str(Path(__file__).with_name("backend_probe.cpp")), "-L", str(args.library.parent),
               "-Wl,-rpath," + str(args.library.parent), "-lmdn", "-o", str(executable)]
    args.build_log.parent.mkdir(parents=True, exist_ok=True)
    with args.build_log.open("a") as log:
        log.write("\nFuzzy backend probe compile: " + shlex.join(command) + "\n")
        log.flush()
        process = subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        for line in process.stdout:
            print(line, end="", flush=True)
            log.write(line)
            log.flush()
        if process.wait() != 0:
            raise RuntimeError("Probe compilation failed; see " + str(args.build_log))
    return command


def check_case(executable, case, args):
    base, sign, n, m, p, q = case
    started = time.monotonic()
    completed = subprocess.run([str(executable), *map(str, case)], check=True, text=True,
                               capture_output=True, timeout=args.case_timeout)
    cells = json.loads(completed.stdout)
    (args.work / ("case_" + "_".join(map(str, case)) + ".json")).write_text(completed.stdout)
    values = {name: grid(raw) for name, raw in cells.items()}
    expected_inputs = {"L_N": cascade(n, "X"), "R_M": cascade(m, "Y"),
                       "L_P": cascade(p, "X"), "R_Q": cascade(q, "Y")}
    checks = {name + "_input": equal_mod_carry(values[name], expected, base)
              for name, expected in expected_inputs.items()}
    factors = {"F": ("L_N", "R_M"), "FX": ("F", "L_P"),
               "FY": ("F", "R_Q"), "F2": ("F", "F")}
    for name, factor_names in factors.items():
        checks[name + "_finite_convolution"] = equal_mod_carry(
            values[name], multiply(*(values[factor] for factor in factor_names)), base)
    for name in ("FX", "FY", "F2"):
        checks[name + "_association"] = equal_mod_carry(values[name], values[name + "_alternate"], base)
    a, b, c, d = (boundary_factor(n + 1), boundary_factor(-m - 1),
                   boundary_factor(p + 1), boundary_factor(-q - 1))
    formulas = {"F": (2, multiply(a, b)), "FX": (3, multiply(a, b, c)),
                "FY": (3, multiply(a, b, d)), "F2": (4, multiply(a, a, b, b))}
    for name, (power, expected) in formulas.items():
        checks[name + "_boundary_identity"] = equal_mod_carry(scale(values[name], base ** power), expected, base)
        checks[name + "_backend_scaled_identity"] = equal_mod_carry(values[f"b{power}{name}"], expected, base)
    return {
        "base": base, "sign": sign, "N": n, "M": m, "P": p, "Q": q,
        "seconds": round(time.monotonic() - started, 4), "checks": checks,
        "nonzero_cell_counts": {name: len(values[name]) for name in GRID_NAMES},
        "raw_association_equal": {name: values[name] == values[name + "_alternate"]
                                  for name in ("FX", "FY", "F2")},
        "boundary_cells": {f"b{power}{name}": sorted([*coordinate, digit] for coordinate, digit in
                                                   values[f"b{power}{name}"].items())
                           for name, (power, _) in formulas.items()},
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--library", type=Path, default=REPOSITORY / "build/fraxis/libmdn.so")
    parser.add_argument("--work", type=Path, default=DEFAULT_WORK)
    parser.add_argument("--build-log", type=Path, default=DEFAULT_LOG)
    parser.add_argument("--compiler", default="c++")
    parser.add_argument("--case-timeout", type=float, default=30)
    parser.add_argument("--quick", action="store_true", help="Only a few representative cases")
    parser.add_argument("--output", type=Path, default=Path(__file__).with_name("backend_results.json"))
    args = parser.parse_args()
    args.library = args.library.resolve()
    args.work.mkdir(parents=True, exist_ok=True)
    executable = args.work / "backend_probe"
    started = time.monotonic()
    command = compile_probe(args, executable)
    if args.quick:
        cases = [(10, 2, 0, 0, 0, 0), (10, 2, 2, 3, 1, 2), (10, 2, 20, 20, 20, 20)]
    else:
        cases = [(10, 2, n, m, p, q) for n, m, p, q in itertools.product(range(3), repeat=4)]
        cases += [(base, sign, n, m, p, q) for base, sign in itertools.product((2, 3, 10, 16), (1, 2, 3))
                  for n, m, p, q in ((0, 0, 0, 0), (2, 3, 1, 4), (4, 1, 3, 2))]
        cases += [(10, 2, *indices) for indices in ((20, 20, 20, 20), (20, 21, 20, 21),
                  (20, 40, 20, 40), (40, 40, 40, 40), (40, 41, 40, 41), (40, 80, 40, 80))]
        cases = list(dict.fromkeys(cases))
    results, failures = [], []
    for index, case in enumerate(cases, 1):
        try:
            row = check_case(executable, case, args)
            results.append(row)
            bad = [name for name, success in row["checks"].items() if not success]
            if bad:
                failures.append({"case": case, "failed_checks": bad})
                print("FAILED", case, bad, flush=True)
            elif index % 20 == 0 or max(case[2:]) >= 20 or args.quick:
                print(f"Passed case {index}/{len(cases)}: {case}; {row['seconds']} s", flush=True)
        except Exception as error:
            failures.append({"case": case, "exception": repr(error)})
            print("FAILED", case, repr(error), flush=True)
    summary = {
        "scope": "Finite grids, all boundary terms retained; precision -1; exact text 0.1 input in each base.",
        "warning": "These checks do not establish an infinite mixed product or a unique canonical digit grid.",
        "library": str(args.library),
        "library_sha256": hashlib.sha256(args.library.read_bytes()).hexdigest(),
        "compiler": subprocess.check_output([args.compiler, "--version"], text=True).splitlines()[0],
        "compile_command": command,
        "dynamic_linkage": subprocess.check_output(["ldd", str(executable)], text=True).splitlines(),
        "python": platform.python_version(), "platform": platform.platform(),
        "runtime_seconds": round(time.monotonic() - started, 3),
        "case_count": len(cases), "completed_case_count": len(results),
        "check_names": sorted({name for row in results for name in row["checks"]}),
        "check_count": sum(len(row["checks"]) for row in results),
        "failed_check_count": sum(not success for row in results for success in row["checks"].values()),
        "failures": failures,
        "raw_association_difference_count": sum(not same for row in results for same in row["raw_association_equal"].values()),
        "full_grids_directory": str(args.work),
        "results": [
            {
                **{name: value for name, value in row.items() if name not in ("checks", "boundary_cells")},
                "checks_passed": sum(row["checks"].values()),
                "failed_checks": [name for name, success in row["checks"].items() if not success],
                **({"boundary_cells": row["boundary_cells"]}
                   if max(row["N"], row["M"], row["P"], row["Q"]) >= 20 else {}),
            }
            for row in results
        ],
    }
    args.output.write_text(json.dumps(summary, indent=2) + "\n")
    print(f"{summary['check_count']} exact checks over {len(results)}/{len(cases)} cases; "
          f"{len(failures)} failures; {summary['runtime_seconds']} s. Summary: {args.output}")
    return bool(failures)


if __name__ == "__main__":
    raise SystemExit(main())
